#!/usr/bin/env python3
"""Deterministic evals for folder-triage: triage_scan, apply_moves (dry, go, undo), folder_check on a
messy and a clean fixture, and the wiring of the Folder discipline rule into the standards, the rules
file template, rules-file, and start. Exit 0 = all pass."""
import os, sys, csv, shutil, subprocess, tempfile
H = os.path.dirname(os.path.abspath(__file__)); P = os.path.join(H, '..', 'plugins', 'officer-kit'); S = os.path.join(P, 'skills', 'folder-triage', 'scripts')
def run(*a): return subprocess.run([sys.executable, *a], capture_output=True, text=True)
res = []
def ok(name, cond): res.append((name, bool(cond)))
def w(p, data=b'x'):
    os.makedirs(os.path.dirname(p), exist_ok=True); open(p, 'wb').write(data)
T = tempfile.mkdtemp(); F = os.path.join(T, 'Work')
blob = os.urandom(4000)
w(f'{F}/Exercises/FEX/Order (draft 1).docx', b'a' * 2000)
w(f'{F}/Exercises/FEX/Order (draft 2).docx', b'b' * 2000)
w(f'{F}/Exercises/FEX/_to_delete/old.md')
w(f'{F}/Exercises/FEX/map.pdf', blob)
w(f'{F}/print/map.pdf', blob)
w(f'{F}/print/Event/notes.md')
w(f'{F}/Exercises/FEX/~$lock.docx')
w(f'{F}/stray.txt')
w(f'{F}/Reference/Order.pdf', os.urandom(3000))
w(f'{F}/Exercises/FEX/To CO 1 Nov/brief.pdf', blob)
os.makedirs(f'{F}/_build', exist_ok=True); shutil.copy(f'{S}/folder_check.py', f'{F}/_build/folder_check.py')
open(f'{F}/_build/folder_check_allow.txt', 'w').write('since: 2000-01-01\nroot: Exercises\nroot: print\nroot: Reference\n')
r = run(f'{F}/_build/folder_check.py'); out = r.stdout
ok('messy folder fails', r.returncode == 1)
for tag in ['DEAD FOLDER', 'ROOT STRAY', 'VERSION NAME', 'VERSIONS', 'JUNK', 'PRINT ROOT', 'PRINT SOURCE', 'DUPLICATE']:
    ok(f'messy folder flags {tag}', tag in out)
ok('sent record and Reference copies not flagged as duplicates', 'To CO' not in out and 'Reference/' not in out)
r = run(f'{S}/triage_scan.py', F); man = list(csv.DictReader(open(f'{F}/_build/triage/manifest.csv', encoding='utf-8')))
acts = {(m['action'], m['from']) for m in man}
ok('scan archives the older draft', ('ARCHIVE', 'Exercises/FEX/Order (draft 1).docx') in acts)
ok('scan keeps the newest draft', not any(m['from'] == 'Exercises/FEX/Order (draft 2).docx' for m in man))
ok('scan renames the dead folder', ('RENAME', 'Exercises/FEX/_to_delete') in acts)
ok('scan archives junk', ('ARCHIVE', 'Exercises/FEX/~$lock.docx') in acts)
ok('scan never touches Reference or sent records', not any(m['from'].startswith('Reference/') or 'To CO' in m['from'] for m in man))
ok('scan keeps the print PDF as the copy', not any(m['from'] == 'print/map.pdf' for m in man))
r = run(f'{S}/apply_moves.py', F, f'{F}/_build/triage/manifest.csv')
ok('dry run moves nothing', 'DRY RUN' in r.stdout and os.path.exists(f'{F}/Exercises/FEX/Order (draft 1).docx'))
r = run(f'{S}/apply_moves.py', F, f'{F}/_build/triage/manifest.csv', '--go')
ok('go moves the draft to _archive', os.path.exists(f'{F}/Exercises/FEX/_archive/Order (draft 1).docx') and not os.path.exists(f'{F}/Exercises/FEX/Order (draft 1).docx'))
ok('go merges the dead folder into _archive', os.path.exists(f'{F}/Exercises/FEX/_archive/old.md') and not os.path.exists(f'{F}/Exercises/FEX/_to_delete'))
ok('go writes a move log', os.path.exists(f'{F}/_build/triage/move_log.csv'))
ok('DECIDE rows wait', os.path.exists(f'{F}/Exercises/FEX/map.pdf'))
r = run(f'{S}/apply_moves.py', F, '--undo', f'{F}/_build/triage/move_log.csv')
ok('undo restores the draft', os.path.exists(f'{F}/Exercises/FEX/Order (draft 1).docx'))
shutil.rmtree(T)
# clean fixture passes
T = tempfile.mkdtemp(); F = os.path.join(T, 'Work')
w(f'{F}/Exercises/FEX/Order.docx'); w(f'{F}/Exercises/FEX/_archive/Order (draft 1, 1 Oct 26).docx')
w(f'{F}/print/FEX/Order card.pdf', os.urandom(3000)); w(f'{F}/Exercises/FEX/Weather Brief (16 to 19 Nov 26).pdf')
w(f'{F}/print/FEX/Cards (rev 1).pdf'); w(f'{F}/print/FEX/Cards (rev 2 additions).pdf')
os.makedirs(f'{F}/_build', exist_ok=True); shutil.copy(f'{S}/folder_check.py', f'{F}/_build/folder_check.py')
open(f'{F}/_build/folder_check_allow.txt', 'w').write('root: Exercises\nroot: print\nprint/FEX/Cards (rev 1).pdf\nprint/FEX/Cards (rev 2 additions).pdf\n')
r = run(f'{F}/_build/folder_check.py')
ok('clean folder passes', r.returncode == 0 and '0 violations' in r.stdout)
if r.returncode: print(r.stdout)
shutil.rmtree(T)
# wiring
std = open(f'{P}/STANDARDS.md').read(); tpl = open(f'{P}/skills/rules-file/references/template.md').read()
ok('standard 1 archives revisions', '_archive' in std.split('2. **Sources only')[0] and 'plain name' in std.split('2. **Sources only')[0])
ok('standard 1 leads with NOT SAVED and stops', 'NOT SAVED to your computer' in std and 'nothing further is built' in std)
ok('template carries Folder discipline with the checker', '## Folder discipline' in tpl and 'folder_check.py' in tpl)
ok('rules-file writes the block at every depth', 'Folder discipline block comes third' in open(f'{P}/skills/rules-file/SKILL.md').read())
ok('start installs the checker', 'folder_check.py' in open(f'{P}/skills/start/SKILL.md').read())
ft = open(f'{P}/skills/folder-triage/SKILL.md').read()
ok('folder-triage drops the old naming pattern', 'YYYY-MM-DD_topic_version' not in ft and '_archive' in ft)
# catalog, path audit, save command (0.30.0)
T = tempfile.mkdtemp(); F = os.path.join(T, 'Work')
for n in ('folder_check.py', 'make_index.py', 'path_audit.py', 'save_product.py', 'apply_moves.py'):
    os.makedirs(f'{F}/_build', exist_ok=True); shutil.copy(f'{S}/{n}', f'{F}/_build/{n}')
open(f'{F}/_build/folder_check_allow.txt', 'w').write('root: Exercises\nroot: print\nroot: Reference\nroot: Notes\nroot: Company\nroot: CLAUDE.md\nalias: C:\\Work\nclosed: Exercises/FEX 1\nnoindex: Exercises/FEX 2/research\nnoaudit: Notes/Cleanup Report.md\n')
w(f'{F}/Exercises/FEX 2/Defense Order.md', b'# Defense Order for the FEX\n')
w(f'{F}/Exercises/FEX 2/research/dump.pdf'); w(f'{F}/Exercises/FEX 2/plot.py'); w(f'{F}/Exercises/FEX 2/_work/scratch.md')
w(f'{F}/Exercises/FEX 1/Brief.pptx'); w(f'{F}/print/FEX 2/Cards.pdf'); w(f'{F}/print/Phase III/Sheet.pdf')
w(f'{F}/Company/Reports/Report.md'); w(f'{F}/Reference/Handout.md', b'See C:\\Work\\FEX 2\\Defense Order.md\n')
note = ('Order: C:\\Work\\FEX 2\\Defense Order.md and C:\\Work\\print\\Cards.pdf, listed card by card in Notes here.\n'
        'Weekly: C:\\Work\\Company\\Phase III notes. Gone: C:\\Work\\Lost\\thing.docx. Folder: C:\\Work\\FEX 1.\n')
w(f'{F}/CLAUDE.md', note.encode()); w(f'{F}/Notes/Cleanup Report.md', note.encode())
r = run(f'{F}/_build/make_index.py'); tsv = open(f'{F}/_build/index.tsv', encoding='utf-8').read()
ok('catalog lists products', 'Exercises/FEX 2/Defense Order.md' in tsv and 'print/FEX 2/Cards.pdf' in tsv)
ok('catalog leaves out code, underscore folders, and noindex folders', 'plot.py' not in tsv and 'scratch.md' not in tsv and 'dump.pdf' not in tsv)
ok('catalog reads the title of a .md', 'Defense Order for the FEX' in tsv)
ok('catalog marks closed events', '\tclosed\t' in [l for l in tsv.splitlines() if 'FEX 1/Brief.pptx' in l][0])
ok('catalog writes INDEX.md at the root', os.path.exists(f'{F}/INDEX.md') and '# Closed events' in open(f'{F}/INDEX.md', encoding='utf-8').read())
r = run(f'{F}/_build/make_index.py', '--find', 'defense', 'order')
ok('find returns the product with the alias path', r.returncode == 0 and 'C:\\Work\\Exercises\\FEX 2\\Defense Order.md' in r.stdout)
r = run(f'{F}/_build/path_audit.py'); out = r.stdout
ok('audit finds a moved file', 'FEX 2/Defense Order.md  -> Exercises/FEX 2/Defense Order.md' in out)
ok('audit finds a moved folder', 'FEX 1  -> Exercises/FEX 1' in out)
ok('audit does not move a generic folder name out of a folder that still exists', 'print/Phase III' not in out)
ok('audit reports a lost path', 'Lost/thing.docx' in out)
os.utime(f'{F}/CLAUDE.md', (1000000000, 1000000000))
r = run(f'{F}/_build/path_audit.py', '--fix'); fixed = open(f'{F}/CLAUDE.md', encoding='utf-8').read()
ok('fix keeps the note\'s modified date', int(os.path.getmtime(f'{F}/CLAUDE.md')) == 1000000000)
ok('fix rewrites the stale paths', 'C:\\Work\\Exercises\\FEX 2\\Defense Order.md' in fixed and 'C:\\Work\\print\\FEX 2\\Cards.pdf' in fixed and 'C:\\Work\\Exercises\\FEX 1.' in fixed)
ok('fix keeps the words between two paths', ', listed card by card in Notes here.' in fixed)
ok('fix leaves noaudit records and issued sources alone', open(f'{F}/Notes/Cleanup Report.md', encoding='utf-8').read() == note and 'C:\\Work\\FEX 2\\' in open(f'{F}/Reference/Handout.md', encoding='utf-8').read())
src = os.path.join(T, 'Defense Order.md'); open(src, 'w').write('# Defense Order, new\n')
r = run(f'{F}/_build/save_product.py', src, 'Exercises/FEX 2', '--version', 'draft 1')
arch = os.listdir(f'{F}/Exercises/FEX 2/_archive') if os.path.isdir(f'{F}/Exercises/FEX 2/_archive') else []
ok('save archives the old version with its label and date', r.returncode == 0 and any(a.startswith('Defense Order (draft 1, ') for a in arch))
ok('save writes the new file under the plain name', 'new' in open(f'{F}/Exercises/FEX 2/Defense Order.md', encoding='utf-8').read() and 'SAVED    C:\\Work\\Exercises\\FEX 2\\Defense Order.md' in r.stdout)
ok('save rebuilds the catalog', 'Defense Order, new' in open(f'{F}/_build/index.tsv', encoding='utf-8').read())
v2 = os.path.join(T, 'Order v2.md'); open(v2, 'w').write('x')
ok('save refuses a version word', run(f'{F}/_build/save_product.py', v2, 'Exercises/FEX 2').returncode == 1)
ok('save refuses the print root', run(f'{F}/_build/save_product.py', src, 'print').returncode == 1)
ok('save refuses the root and underscore folders', run(f'{F}/_build/save_product.py', src, '').returncode == 1 and run(f'{F}/_build/save_product.py', src, 'Exercises/FEX 2/_work').returncode == 1)
ok('save leaves an identical file alone', 'UNCHANGED' in run(f'{F}/_build/save_product.py', src, 'Exercises/FEX 2').stdout)
r = run(f'{F}/_build/folder_check.py')
ok('folder check accepts INDEX.md and the new allow lines', 'STRAY   INDEX.md' not in r.stdout and 'alias' not in r.stdout and 'closed:' not in r.stdout)
shutil.rmtree(T)
std1 = std.split('2. **Sources only')[0]
ok('standard 1 names the save command', 'save_product.py' in std1)
ok('standard 11 searches the catalog first', 'INDEX.md' in std.split('11. **')[1])
ok('template carries the catalog, save command, and path audit', all(x in tpl for x in ('make_index.py --find', 'save_product.py', 'path_audit.py --fix', 'closed: <folder>')))
ok('start installs the four scripts', all(x in open(f'{P}/skills/start/SKILL.md').read() for x in ('make_index.py', 'path_audit.py', 'save_product.py')))
ok('folder-triage runs the audit and offers the weekly task', 'path_audit.py --fix' in ft and 'scheduled task' in ft)
ok('after-action offers close out', 'closed: <the event' in open(f'{P}/skills/after-action/SKILL.md').read())
fails = [n for n, v in res if not v]
for n, v in res: print(('PASS ' if v else 'FAIL ') + n)
print(f'\n{len(res) - len(fails)}/{len(res)} passed')
sys.exit(1 if fails else 0)
